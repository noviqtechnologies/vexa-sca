use crate::patcher::lockfile_patcher::PatchResult;
use chrono::Utc;
use reqwest::header::{HeaderMap, HeaderValue, ACCEPT, AUTHORIZATION, USER_AGENT};
use serde::{Deserialize, Serialize};
use serde_json::json;
use std::env;
use std::path::Path;
use std::process::Command;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct GitRepoInfo {
    pub owner: String,
    pub repo: String,
    pub remote_url: String,
    pub current_branch: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PrResult {
    pub branch: String,
    pub pr_url: Option<String>,
    pub pr_number: Option<u64>,
    pub committed: bool,
    pub pushed: bool,
    pub message: String,
}

pub struct PrCreator;

impl PrCreator {
    /// Detects git repository info and current GitHub owner/repo from remote URL.
    pub fn detect_repo_info(project_dir: &Path) -> Result<GitRepoInfo, String> {
        // 1. Verify git repo
        let is_git = Command::new("git")
            .arg("rev-parse")
            .arg("--is-inside-work-tree")
            .current_dir(project_dir)
            .output()
            .map_err(|e| format!("Failed to run git command: {}. Ensure git is installed.", e))?;

        if !is_git.status.success() {
            return Err(format!("{} is not a git repository", project_dir.display()));
        }

        // 2. Get current branch
        let branch_output = Command::new("git")
            .args(["rev-parse", "--abbrev-ref", "HEAD"])
            .current_dir(project_dir)
            .output()
            .map_err(|e| format!("Failed to read git branch: {}", e))?;

        let current_branch = String::from_utf8_lossy(&branch_output.stdout)
            .trim()
            .to_string();
        let current_branch = if current_branch.is_empty() || current_branch == "HEAD" {
            "main".to_string()
        } else {
            current_branch
        };

        // 3. Get remote URL
        let remote_output = Command::new("git")
            .args(["config", "--get", "remote.origin.url"])
            .current_dir(project_dir)
            .output()
            .map_err(|e| format!("Failed to read git remote origin URL: {}", e))?;

        let remote_url = String::from_utf8_lossy(&remote_output.stdout)
            .trim()
            .to_string();
        if remote_url.is_empty() {
            return Err("No remote origin URL found in git repository".to_string());
        }

        let (owner, repo) = Self::parse_github_url(&remote_url)?;

        Ok(GitRepoInfo {
            owner,
            repo,
            remote_url,
            current_branch,
        })
    }

    /// Parses owner and repo name from GitHub URLs (https or ssh).
    pub fn parse_github_url(url: &str) -> Result<(String, String), String> {
        let clean = url.trim().trim_end_matches(".git");

        // SSH format: git@github.com:owner/repo
        if let Some(pos) = clean.find(':') {
            let path_part = &clean[pos + 1..];
            let parts: Vec<&str> = path_part.split('/').collect();
            if parts.len() >= 2 {
                let owner = parts[parts.len() - 2].to_string();
                let repo = parts[parts.len() - 1].to_string();
                return Ok((owner, repo));
            }
        }

        // HTTPS format: https://github.com/owner/repo
        if let Some(pos) = clean.find("github.com/") {
            let path_part = &clean[pos + "github.com/".len()..];
            let parts: Vec<&str> = path_part.split('/').collect();
            if parts.len() >= 2 {
                let owner = parts[0].to_string();
                let repo = parts[1].to_string();
                return Ok((owner, repo));
            }
        }

        Err(format!(
            "Could not extract GitHub owner/repo from URL: {}",
            url
        ))
    }

    /// Generates structured PR Markdown content from applied patches.
    pub fn generate_pr_body(patch_res: &PatchResult) -> String {
        let mut body = String::new();
        body.push_str("## 🛡️ Vexa SCA Security Remediation\n\n");
        body.push_str("This automated Pull Request was generated by **Vexa SCA** to remediate known vulnerabilities in application dependencies.\n\n");

        if !patch_res.changes.direct_upgrades.is_empty() {
            body.push_str("### ⬆️ Direct Dependency Upgrades\n\n");
            body.push_str("| Package | Current Version | Upgraded Version | Section | Type | Advisory Fixes |\n");
            body.push_str("| :--- | :--- | :--- | :--- | :--- | :--- |\n");
            for u in &patch_res.changes.direct_upgrades {
                let badge = if u.is_breaking {
                    "⚠️ **MAJOR (Breaking)**"
                } else if !u.semver_change.is_empty() {
                    match u.semver_change.as_str() {
                        "PATCH" => "✔ Patch",
                        "MINOR" => "✔ Minor",
                        _ => "✔ SemVer-compatible",
                    }
                } else {
                    "✔ Safe Upgrade"
                };
                let vulns = if u.vulnerability_ids.is_empty() {
                    "—".to_string()
                } else {
                    u.vulnerability_ids.join(", ")
                };
                body.push_str(&format!(
                    "| `{}` | `{}` | `^`**{}** | `{}` | {} | {} |\n",
                    u.package, u.from, u.to, u.section, badge, vulns
                ));
            }
            body.push('\n');
        }

        if !patch_res.changes.transitive_overrides.is_empty() {
            body.push_str("### 🔒 Transitive Overrides & Lockfile Updates\n\n");
            body.push_str("| Package | Forced Secure Version | Advisory Fixes |\n");
            body.push_str("| :--- | :--- | :--- |\n");
            for o in &patch_res.changes.transitive_overrides {
                let vulns = if o.vulnerability_ids.is_empty() {
                    "—".to_string()
                } else {
                    o.vulnerability_ids.join(", ")
                };
                body.push_str(&format!(
                    "| `{}` | `^{}` | {} |\n",
                    o.package, o.pinned_to, vulns
                ));
            }
            body.push('\n');
        }

        body.push_str("---\n\n");
        body.push_str("### 🔍 Verification Instructions\n");
        body.push_str("1. Review the modified manifest file(s).\n");
        body.push_str("2. Run package manager commands to regenerate lockfiles & run tests:\n");
        body.push_str("   ```bash\n   # Cargo (Rust):\n   cargo check && cargo test\n\n   # Node.js (npm / yarn / pnpm):\n   npm install && npm test\n\n   # Python (pip):\n   pip install -r requirements.txt && pytest\n   ```\n\n");
        body.push_str("*(Created automatically by Vexa SCA engine)*\n");

        body
    }

    /// Creates git branch, commits changes, and opens a GitHub Pull Request.
    pub async fn create_and_open_pr(
        project_dir: &Path,
        patch_res: &PatchResult,
        target_repo: Option<String>,
        branch_name: Option<String>,
        base_branch: Option<String>,
        token: Option<String>,
        dry_run: bool,
    ) -> Result<PrResult, String> {
        let repo_info = Self::detect_repo_info(project_dir).ok();

        let (owner, repo) = if let Some(r) = target_repo {
            let parts: Vec<&str> = r.split('/').collect();
            if parts.len() == 2 {
                (parts[0].to_string(), parts[1].to_string())
            } else {
                return Err("Repository must be in format 'owner/repo'".to_string());
            }
        } else if let Some(info) = &repo_info {
            (info.owner.clone(), info.repo.clone())
        } else {
            return Err(
                "Could not auto-detect GitHub repository. Specify with --repo <owner/repo>"
                    .to_string(),
            );
        };

        let base = base_branch
            .or_else(|| repo_info.as_ref().map(|i| i.current_branch.clone()))
            .unwrap_or_else(|| "main".to_string());

        let branch = branch_name.unwrap_or_else(|| {
            format!(
                "vexa-sca/fix-vulnerabilities-{}",
                Utc::now().format("%Y%m%d%H%M%S")
            )
        });

        let title = "fix(deps): security vulnerability fixes by Vexa SCA".to_string();
        let body = Self::generate_pr_body(patch_res);

        if dry_run {
            return Ok(PrResult {
                branch,
                pr_url: None,
                pr_number: None,
                committed: false,
                pushed: false,
                message: format!(
                    "[Dry Run] Prepared PR for {}/{} (base: {}) with title: \"{}\"",
                    owner, repo, base, title
                ),
            });
        }

        // 1. Create and checkout new branch
        let checkout_res = Command::new("git")
            .args(["checkout", "-b", &branch])
            .current_dir(project_dir)
            .output()
            .map_err(|e| format!("Failed to create git branch {}: {}", branch, e))?;

        if !checkout_res.status.success() {
            let err = String::from_utf8_lossy(&checkout_res.stderr);
            return Err(format!("git checkout -b failed: {}", err));
        }

        // 2. Stage modified manifest and lock files
        let manifest_candidates = [
            "package.json",
            "package-lock.json",
            "yarn.lock",
            "pnpm-lock.yaml",
            "Cargo.toml",
            "Cargo.lock",
        ];
        for file in &manifest_candidates {
            if project_dir.join(file).exists() {
                let _ = Command::new("git")
                    .args(["add", file])
                    .current_dir(project_dir)
                    .output();
            }
        }

        // 3. Commit changes
        let commit_res = Command::new("git")
            .args(["commit", "-m", &title])
            .current_dir(project_dir)
            .output()
            .map_err(|e| format!("Failed to git commit: {}", e))?;

        if !commit_res.status.success() {
            let err = String::from_utf8_lossy(&commit_res.stderr);
            return Err(format!("git commit failed: {}", err));
        }

        // 4. Resolve token
        let auth_token = token
            .or_else(|| env::var("GITHUB_TOKEN").ok())
            .or_else(|| env::var("GH_TOKEN").ok());

        // 5. Push branch to remote
        let push_res = Command::new("git")
            .args(["push", "-u", "origin", &branch])
            .current_dir(project_dir)
            .output();

        let pushed = push_res.map(|o| o.status.success()).unwrap_or(false);

        // 6. Open Pull Request via GitHub REST API if token available
        if let Some(tok) = auth_token {
            if pushed {
                let client = reqwest::Client::new();
                let mut headers = HeaderMap::new();
                headers.insert(USER_AGENT, HeaderValue::from_static("vexa-sca"));
                headers.insert(
                    ACCEPT,
                    HeaderValue::from_static("application/vnd.github+json"),
                );

                if let Ok(val) = HeaderValue::from_str(&format!("Bearer {}", tok.trim())) {
                    headers.insert(AUTHORIZATION, val);
                }

                let pr_endpoint = format!("https://api.github.com/repos/{}/{}/pulls", owner, repo);
                let payload = json!({
                    "title": title,
                    "head": branch,
                    "base": base,
                    "body": body
                });

                let resp = client
                    .post(&pr_endpoint)
                    .headers(headers)
                    .json(&payload)
                    .send()
                    .await;

                match resp {
                    Ok(r) if r.status().is_success() => {
                        let json_val: serde_json::Value = r.json().await.unwrap_or_default();
                        let html_url = json_val
                            .get("html_url")
                            .and_then(|u| u.as_str())
                            .map(|s| s.to_string());
                        let number = json_val.get("number").and_then(|n| n.as_u64());

                        return Ok(PrResult {
                            branch,
                            pr_url: html_url.clone(),
                            pr_number: number,
                            committed: true,
                            pushed: true,
                            message: format!(
                                "Pull Request successfully created: {}",
                                html_url.unwrap_or_else(|| "N/A".to_string())
                            ),
                        });
                    }
                    Ok(r) => {
                        let status = r.status();
                        let text = r.text().await.unwrap_or_default();
                        return Ok(PrResult {
                            branch: branch.clone(),
                            pr_url: None,
                            pr_number: None,
                            committed: true,
                            pushed: true,
                            message: format!(
                                "Branch pushed, but GitHub API returned HTTP {}: {}. Create PR manually: https://github.com/{}/{}/compare/{}...{}",
                                status, text, owner, repo, base, branch
                            ),
                        });
                    }
                    Err(e) => {
                        return Ok(PrResult {
                            branch: branch.clone(),
                            pr_url: None,
                            pr_number: None,
                            committed: true,
                            pushed: true,
                            message: format!("Branch pushed. Failed to contact GitHub API: {}", e),
                        });
                    }
                }
            }
        }

        Ok(PrResult {
            branch: branch.clone(),
            pr_url: None,
            pr_number: None,
            committed: true,
            pushed,
            message: format!(
                "Security patches committed to branch '{}'. Open PR manually or provide GITHUB_TOKEN: https://github.com/{}/{}/compare/{}...{}",
                branch, owner, repo, base, branch
            ),
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::patcher::lockfile_patcher::{DirectUpgrade, PatchChanges, TransitiveOverride};

    #[test]
    fn test_parse_github_url_ssh_and_https() {
        let (o1, r1) = PrCreator::parse_github_url("git@github.com:my-org/my-project.git").unwrap();
        assert_eq!(o1, "my-org");
        assert_eq!(r1, "my-project");

        let (o2, r2) =
            PrCreator::parse_github_url("https://github.com/vexa-sca/core-scanner.git").unwrap();
        assert_eq!(o2, "vexa-sca");
        assert_eq!(r2, "core-scanner");

        let (o3, r3) = PrCreator::parse_github_url("https://github.com/developer/app").unwrap();
        assert_eq!(o3, "developer");
        assert_eq!(r3, "app");
    }

    #[test]
    fn test_generate_pr_body_formatting() {
        let mut changes = PatchChanges::default();
        changes.direct_upgrades.push(DirectUpgrade {
            package: "lodash".to_string(),
            from: "4.17.15".to_string(),
            to: "4.17.21".to_string(),
            section: "dependencies".to_string(),
            ..Default::default()
        });
        changes.transitive_overrides.push(TransitiveOverride {
            package: "minimist".to_string(),
            pinned_to: "1.2.8".to_string(),
            ..Default::default()
        });

        let patch_res = PatchResult {
            modified: true,
            backup_file: None,
            changes,
            warnings: vec![],
        };

        let body = PrCreator::generate_pr_body(&patch_res);
        assert!(body.contains("Direct Dependency Upgrades"));
        assert!(body.contains("lodash"));
        assert!(body.contains("4.17.21"));
        assert!(body.contains("Transitive Overrides"));
        assert!(body.contains("minimist"));
        assert!(body.contains("1.2.8"));
    }
}
